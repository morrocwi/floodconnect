# No-hosted-access change (2026-10-04, project decision): this repo ships NO
# pre-computed `site/dist/api/v1/**` export any more (not tracked in git, not part of
# any release). A caller who has not yet run the local export pipeline on their own
# machine gets an honest UNKNOWN + a concrete next_action here, never a bare
# protocol-level error and never a value read from a shipped snapshot.
_RUN_EXPORT_ACTION = (
    "no local export found under FLOODCONNECT_API_BASE -- run 'collect.py --all' then "
    "'python3 site/build_data.py' then 'python3 tools/api/export_api.py "
    "--data-json site/dist/data.json --typology-graph output/typology_graph.json "
    "--typology-subgraph-dir output --self-help-dag site/inputs/community/"
    "self_help_dag.yaml --sources-registry sources/registry.yaml --out-dir "
    "site/dist/api/v1' on your own machine, network and keys -- or call "
    "floodconnect_answer instead, which reads data/observations.sqlite directly."
)


def _known_area_ids() -> "list[str]":
    """Reuses `kb.py`'s own `_ANSWER_AREAS` keys (never a second hard-coded area
    list) so `get_area_state` can tell a genuinely unknown area_id apart from a
    known one whose export just hasn't been generated locally yet."""
    try:
        import kb as kb_mod
        return sorted(kb_mod._ANSWER_AREAS)
    except Exception:  # pragma: no cover - defensive, kb.py must not be required to import
        return []


def list_areas(base: str) -> dict:
    try:
        index = _read(base, "index.json")
    except FloodConnectMCPError:
        return _with_epistemic_envelope(
            {"areas": [], "next_action": _RUN_EXPORT_ACTION},
            source="index.json", observed_at=None, tag="OPEN",
        )
    areas = []
    for area_id in index.get("areas", []):
        try:
            area = _read(base, f"areas/{area_id}.json")
            areas.append({"area_id": area_id, "label": area.get("label")})
        except FloodConnectMCPError:
            areas.append({"area_id": area_id, "label": None})
    return _with_epistemic_envelope(
        {"areas": areas}, source="index.json",
        observed_at=index.get("generated_at_utc"), tag="MEASURED",
    )


def get_area_state(base: str, area_id: str) -> dict:
    try:
        area = _read(base, f"areas/{area_id}.json")
    except FloodConnectMCPError:
        if area_id in _known_area_ids():
            # A known area with no local export yet -- UNKNOWN + refresh action,
            # never an error that reads as "this place doesn't exist".
            # 2026-10-04 fix: the old return only had `next_action` +
            # the envelope's `tag: OPEN` -- a caller reading only the fields every
            # OTHER `get_area_state` response has (`current_local_state`/
            # `forward_hazard`) saw neither key at all, never an explicit UNKNOWN.
            return _with_epistemic_envelope(
                {"area_id": area_id, "current_local_state": "UNKNOWN",
                 "forward_hazard": "UNKNOWN", "next_action": _RUN_EXPORT_ACTION},
                source=f"areas/{area_id}.json", observed_at=None, tag="OPEN",
            )
        raise FloodConnectMCPError("AREA_NOT_FOUND", f"unknown area_id: {area_id!r}")
    # Recompute fix: recompute every staleness/age_class field against the real
    # wall-clock call time before building the payload below -- see
    # `_recompute_area_freshness`'s own docstring for why the baked file values are
    # never trusted directly.
    area = _recompute_area_freshness(area)
    current_local_state = area.get("current_local_state")
    # FIX B item 4 (2026-10-04): `water_balance` (PROP-FLOOD-03) REFUSES for every
    # served area today -- both village *.balance.yaml declare A/c/C_pump/S0 as OPEN
    # (see `site/build_data.py::build_village_water_balance`'s own docstring), so a
    # caller reading only `status: REFUSED`/`reason_codes` here had no plain-language
    # pointer to what DOES exist. Say so plainly and point at `floodconnect_answer`,
    # never silently leave the caller with a bare REFUSED and no next step.
    if isinstance(current_local_state, dict):
        wb = current_local_state.get("water_balance")
        if isinstance(wb, dict) and wb.get("status") == "REFUSED":
            wb["note"] = (
                "water_balance (PROP-FLOOD-03) is not computed in v0.1.x -- both "
                "served villages declare A/c/C_pump/S0 as OPEN, so this always "
                "REFUSES by design, not a bug; call floodconnect_answer instead for a "
                "real computed reading (state/hazard/accountability/next_action)."
            )
    payload = {
        "area_id": area.get("area_id"),
        "label": area.get("label"),
        "current_local_state": current_local_state,
        "forward_hazard": area.get("forward_hazard"),
        "contradictions": area.get("contradictions", []),
        "safety": area.get("safety"),
        "data_freshness": area.get("data_freshness"),
        # FIX B (2026-10-04): carry the recomputed snapshot markers into the
        # payload itself -- a caller reading only `payload` (not the intermediate
        # `area` dict) must still be able to see this is a retained snapshot and
        # when it was generated, same as `_recompute_area_freshness` sets them.
        "snapshot": area.get("snapshot"),
        "snapshot_generated_at": area.get("snapshot_generated_at"),
    }
    tag = (area.get("data_freshness") or {}).get("overall_age_class")
    tag = {"fresh": "MEASURED", "stale": "MEASURED", "expired": "OPEN"}.get(tag, "OPEN")
    return _with_epistemic_envelope(
        payload, source=f"areas/{area_id}.json",
        observed_at=area.get("generated_at_bkk"), tag=tag,
    )


def get_station(base: str, code: str) -> dict:
    """UNKNOWN is never SAFE (spec sec. 3.3): a code not found anywhere
    returns {"found": false, "tag": "OPEN"}, never a bare false/null and
    never inferred as 'no flooding'."""
    index = _read(base, "index.json")
    for area_id in index.get("areas", []):
        try:
            area = _read(base, f"areas/{area_id}.json")
        except FloodConnectMCPError:
            continue
        # Recompute fix: same live recompute as `get_area_state` -- a station's baked
        # `staleness.age_class`/`tag` must never be trusted as of the real call time.
        area = _recompute_area_freshness(area)
        for canal in (area.get("current_local_state") or {}).get("canals", []):
            if canal.get("station_code") == code:
                return _with_epistemic_envelope(
                    {"found": True, "area_id": area_id, "station": canal},
                    source=f"areas/{area_id}.json",
                    observed_at=canal.get("staleness", {}).get("observed_at"),
                    tag=canal.get("staleness", {}).get("tag", "OPEN"),
                )
    return {
        "found": False,
        "tag": "OPEN",
        "source": "index.json + areas/*.json",
        "staleness": {"observed_at": None, "tag": "OPEN"},
    }


def get_typology_subgraph(base: str, area_id: str) -> dict:
    try:
        sub = _read(base, f"typology/subgraph/{area_id}.json")
    except FloodConnectMCPError:
        raise FloodConnectMCPError("AREA_NOT_FOUND", f"no typology subgraph for area_id: {area_id!r}")
    return _with_epistemic_envelope(
        sub, source=f"typology/subgraph/{area_id}.json",
        observed_at=sub.get("generated_at_bkk"), tag="RELAYED",
    )


def find_safe_route(base: str, zone_id: str, mode: str, group_size: int) -> dict:
    """Maps the exported `community/self_help_dag.json` snapshot onto
    `community_dag.find_safe_route` -- the single canonical route function
    (AI.md section 2: "never re-implemented"). This tool performs no routing
    logic of its own: it only builds the doc the canonical function expects
    and translates its `RouteResult` into the MCP envelope. A partially-
    verified route is never returned silently (spec sec. 3.3); an UNSAFE or
    stale node is rejected by the canonical function's own hard constraints,
    not by anything re-derived here."""
    dag = _read(base, "community/self_help_dag.json")
    doc = {"nodes": dag.get("nodes") or {}, "edges": dag.get("edges") or []}
    observed_at = dag.get("generated_at_bkk")

    result = community_dag.find_safe_route(
        doc, zone_id, mode=mode, group_size=group_size,
    )

    if not result.found:
        return {
            "result": "NO_FEASIBLE_SAFE_ROUTE",
            "reason": result.reason,
            "checked_nodes": list(result.path),
            "source": "community/self_help_dag.json",
            "staleness": {"observed_at": observed_at, "tag": "OPEN"},
        }

    return _with_epistemic_envelope(
        {"result": "ROUTE_FOUND", "path": list(result.path), "target": result.target,
         "checked_nodes": list(result.path), "mode": mode, "group_size": group_size},
        source="community/self_help_dag.json",
        observed_at=observed_at, tag="MEASURED",
    )


def list_upstream_sources(base: str, agency: str | None = None) -> dict:
    sources = _read(base, "sources.json")
    rows = sources.get("sources", [])
    if agency:
        needle = agency.lower()
        rows = [s for s in rows
                if needle in (s.get("agency_en") or "").lower()
                or needle in (s.get("agency_th") or "").lower()]
    return _with_epistemic_envelope(
        {"sources": rows}, source="sources.json", observed_at=None, tag="RELAYED",
    )


def floodconnect_answer_core(at: str, refresh: "bool | None" = None,
                              offline: bool = False, verbose: bool = False) -> dict:
    """The MCP equivalent of `floodconnect answer --refresh` -- every OTHER tool here
    reads the static `site/dist/api/v1` export (Component A), but this one runs the
    richer compute call (state + hazard + accountability + next_action + cctv +
    source_tags, AI.md's one compute call) and its on-demand refresh directly. `cctv`
    (added 2026-10-04, F8) lists up to 3 nearest CCTV cameras, tagged `VISUAL-CHECK` --
    a human-look-yourself reference, never an input to `state`/`hazard`/`next_action`'s
    own classification. This imports `kb` directly (it is on
    `sys.path` via `_REPO_ROOT`, inserted at module load above) and calls
    `kb.build_answer` in-process -- the SAME function `floodconnect answer`'s own
    `cmd_answer` CLI calls, never a second implementation. ONE GET per relevant source,
    on THIS machine's own network/keys (never ours), no scheduler, no retry loop -- see
    `kb._refresh_relevant_sources` and the self-install project decision. A bad `at`
    raises `kb._BadAt`; this wraps that into the same typed `FloodConnectMCPError`
    every other tool here uses, instead of leaking a raw traceback to the MCP
    transport.

    Refresh-by-default (project decision 2026-10-03): when `refresh` is left at its
    default (`None`), this fetches the relevant wired sources before computing UNLESS
    `offline=True` -- same policy as `floodconnect answer` (CLI). Passing `refresh`
    explicitly (`True`/`False`) keeps the old opt-in behaviour for backward
    compatibility with existing callers that already decide for themselves; `offline`
    is then ignored."""
    import kb  # noqa: E402 -- _REPO_ROOT is already on sys.path (see module top)
    effective_refresh = (not offline) if refresh is None else refresh
    try:
        return kb.build_answer(at, refresh=effective_refresh, verbose=verbose)
    except kb._BadAt as e:
        raise FloodConnectMCPError("BAD_AT", str(e)) from e


def floodconnect_locate_core(at: str, province: "str | None" = None) -> dict:
    """The MCP equivalent of `floodconnect locate --at lat,lon [--province X]`
    (M4, "KG-first that AIs cannot skip"). Offline, reads only
    `output/kg_index/` -- no network, no graphml read, <3s. Resolves `at` to
    its province (from `province`, the CALLER's own geocoding decision, or up
    to 3 RELAYED candidates when omitted), nearest sub-basin(s)/assets/reach,
    stations, agencies, known_gaps, and a compact `kg_anchor`. A bad `at`
    raises the same typed `FloodConnectMCPError` every other tool here uses;
    a missing `output/kg_index/` raises `MISSING_KG_INDEX` rather than
    guessing."""
    from tools.kg.locate import KGIndexMissing, locate as _locate

    try:
        lat_s, lon_s = at.split(",")
        lat, lon = float(lat_s), float(lon_s)
    except ValueError as e:
        raise FloodConnectMCPError("BAD_AT", f"--at must be 'lat,lon', got {at!r}") from e
    try:
        return _locate(lat, lon, province=province)
    except KGIndexMissing as e:
        raise FloodConnectMCPError("MISSING_KG_INDEX", str(e)) from e


