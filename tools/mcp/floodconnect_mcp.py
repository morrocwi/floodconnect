#!/usr/bin/env python3
"""tools/mcp/floodconnect_mcp.py -- FloodConnect MCP server (Component B).

Stdio MCP server exposing FloodConnect's local API v1 export (Component A,
tools/api/export_api.py -> site/dist/api/v1/**) to an external AI assistant.
Local files only (project decision 2026-10-04, no-hosted-access): this repo ships
no pre-computed export and no hosted/remote FLOODCONNECT_API_BASE is accepted --
strictly read-only, no tool writes, no collect.py invocation, no network call of
any kind. The export is generated by the installer on their own machine; a
missing export returns OPEN with a "run refresh locally" action instead.

Core logic lives in plain functions (`list_areas`, `get_area_state`, ...)
that take an explicit `base` argument, so tests can call them directly
without spinning up a transport. The `@mcp.tool()`-decorated wrappers at the
bottom read FLOODCONNECT_API_BASE once and delegate to those functions --
this is also where the shared `_with_epistemic_envelope` helper is applied,
so no single tool can forget it.

Falls back to a minimal stdlib JSON-RPC responder if the `mcp` package is not
importable, so this degrades rather than hard-fails in an environment
without the SDK (spec sec. 3.2).
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

import community_dag  # noqa: E402 -- the single canonical route function (AI.md section 2)

# This used to be the bare relative string
# "site/dist/api/v1", resolved against the MCP CLIENT's own current working
# directory (whatever launched this stdio process), not this repo. An MCP client
# almost never has THIS repo as its cwd, so `_resolve_base()` silently pointed at a
# nonexistent path on a fresh clone. Anchoring to `_REPO_ROOT` (this file's own
# location, three levels up) makes the default correct regardless of the caller's
# cwd. This repo ships NO pre-computed export -- the path below does not exist
# until the installer runs collect.py --all, site/build_data.py and
# tools/api/export_api.py on their own machine (or calls `floodconnect_answer`,
# which reads data/observations.sqlite directly and refreshes by default); until
# then every tool here returns OPEN with that same instruction. An explicit
# `FLOODCONNECT_API_BASE` env override may only be a local path -- a hosted/remote
# URL is refused (see `_read()` below, project decision 2026-10-04).
DEFAULT_BASE = str(_REPO_ROOT / "site" / "dist" / "api" / "v1")

# The rule TEXT lives in exactly one place -- AI.md's
# "Mandatory reasoning rules" section -- never duplicated as a second local
# constant here. `explain_rules()` below loads that section at runtime
# instead. The fixed five-value tag vocabulary is also stated once, in
# AI.md's compute-call section, and imported from the single shared
# tag_vocabulary module (see that file's docstring) -- never redeclared here.
from tag_vocabulary import TAG_VOCABULARY  # noqa: E402 -- _REPO_ROOT is already on sys.path
_AI_MD_PATH = _REPO_ROOT / "AI.md"
_RULES_SECTION_MARKER = "## Mandatory reasoning rules"


def _load_rules_text_from_ai_md() -> str | None:
    """Reads AI.md's rules section at call time rather than caching a
    second copy -- if AI.md moves or is renamed, this degrades to None
    (surfaced as tag: OPEN below) instead of silently going stale."""
    try:
        text = _AI_MD_PATH.read_text(encoding="utf-8")
    except OSError:
        return None
    start = text.find(_RULES_SECTION_MARKER)
    if start == -1:
        return None
    rest = text[start:]
    end = rest.find("\n## ", len(_RULES_SECTION_MARKER))
    return rest[:end].strip() if end != -1 else rest.strip()


class FloodConnectMCPError(Exception):
    """Typed error -- carries a code, never raw exception text that could
    leak a local path. Caught at the tool boundary and turned into a typed
    response, not an uncaught exception reaching the transport."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def _with_epistemic_envelope(payload: dict, source: str, observed_at: str | None, tag: str) -> dict:
    """Shared response-wrapper (spec sec. 3.3): every tool response carries
    source/observed_at (staleness)/tag -- applied here once so it can't be
    forgotten in one tool and not another."""
    return {
        **payload,
        "source": source,
        "staleness": {"observed_at": observed_at, "tag": tag},
    }


def _read_local(base: Path, rel_path: str) -> Any:
    p = base / rel_path
    if not p.exists():
        raise FloodConnectMCPError("NOT_FOUND", f"no such published file: {rel_path}")
    return json.loads(p.read_text(encoding="utf-8"))


def _read(base: str, rel_path: str) -> Any:
    # Project decision 2026-10-04 (no-hosted-access): this server reads ONLY a local
    # export the caller generated on their own machine. An http(s) FLOODCONNECT_API_BASE
    # used to fetch someone else's hosted copy with a single GET -- that is itself a
    # hosted-access channel, which the ruling removes. A URL base is now refused
    # outright: OPEN, with the same "run refresh locally" action every other missing-export
    # path returns, never a network fetch.
    if base.startswith("http://") or base.startswith("https://"):
        raise FloodConnectMCPError(
            "OPEN",
            "FLOODCONNECT_API_BASE must be a local path -- hosted/remote export access "
            "is disabled by project decision; run 'floodconnect answer --refresh' (or "
            "collect.py --all + site/build_data.py + tools/api/export_api.py) on your "
            "own machine instead.",
        )
    return _read_local(Path(base), rel_path)


def _resolve_base() -> str:
    return os.environ.get("FLOODCONNECT_API_BASE", DEFAULT_BASE)


# ---------------------------------------------------------------------------
# Build-time snapshot staleness fix (2026-10-04): `site/dist/api/v1/areas/<id>.json` is a
# point-in-time BUILD-TIME snapshot -- its own `data_freshness`/`staleness`/
# `age_class` fields were computed once, when `site/build_data.py` last ran, and then
# committed/redeployed unchanged on every later push. MEASURED later
# via a real MCP client ~30 hours after that build: `get_area_state` still
# reported `age_class: "fresh"`/`stale: false` on a canal reading that was by then a
# day and a half old, and `forward_hazard` still read as an un-dated, un-staled
# "ฝนกำลังจะเบาลงหลัง 22:00 น." narrative. Every staleness field this tool returns is
# now RECOMPUTED against the REAL wall-clock call time below, never trusted from the
# file as-is -- the baked fields are still read (as the `observed_at` input), just
# never taken as the final verdict.
# ---------------------------------------------------------------------------
import datetime as _dt  # noqa: E402

import live_water_level as _lwl  # noqa: E402 -- the ONE freshness gate, see its own module docstring

_MCP_RECOMPUTE_FUTURE_TOLERANCE_H = -1.0  # real wall-clock call time, same default as
                                           # `lwl.is_fresh`'s own (see live_water_level.py)


def _recompute_staleness(observed_at: "str | None", max_age_h: float = _lwl.STALE_HOURS) -> dict:
    """Recompute `{observed_at, age_h, age_class, stale, tag}` against the REAL
    wall-clock call time -- never the file's own baked `generated_at_bkk`/age fields.
    `age_class` mirrors `site/build_data.py:age_class` (fresh|stale|expired) without
    importing that module (it is not on the MCP server's own dependency path and pulls
    in the full collect.py stack) -- same STALE_HOURS cutoff, same `lwl.age_hours`."""
    now_iso = _dt.datetime.now(_dt.timezone.utc).isoformat()
    fresh, age_h = _lwl.is_fresh(observed_at, now_iso, max_age_h,
                                  future_tolerance_h=_MCP_RECOMPUTE_FUTURE_TOLERANCE_H)
    if age_h is None:
        age_class = "expired"
    elif not fresh:
        age_class = "stale"
    else:
        age_class = "fresh"
    return {
        "observed_at": observed_at,
        "age_h": age_h,
        "age_class": age_class,
        "stale": age_class != "fresh",
        "tag": "MEASURED" if age_class != "expired" else "OPEN",
        "recomputed_at": now_iso,
    }


# Stale forward_hazard field drop (2026-10-04): the fields a stale forward_hazard must
# drop -- every one the a later audit MEASURED as still present on a 31h-old
# snapshot (`forecast.available`, `direction`, `trend_word`, `next*_mm`, undated
# `items`/`hourly`/`hourly_full`). `available`/`status` are set to a stale-aware
# value below rather than left in this list, since callers branch on them.
_STALE_FORECAST_FIELDS = (
    "direction", "trend_word", "next6h_mm", "next24h_mm", "h24_48_mm", "h48_72_mm",
    "first_dry_6h_start", "items", "hourly", "hourly_full",
)
_STALE_FORECAST_72H_FIELDS = ("value_mm", "model_id", "model_th")
# The layer0 in/out rows carry the SAME forecast prose baked as free text
# (`text_th`, e.g. "พรุ่งนี้ 2 มม. · รวม 7 วัน 68 มม."), tagged by the one shared
# provenance label third-party forecast rows always use (`tag_th`). Suppressing by
# that tag, not by `label_th` guesswork, catches every model row without a second
# hard-coded model-name list.
_LAYER0_FORECAST_TAG_TH = "ข่าว/บุคคลที่สาม"
_STALE_TEXT_TH = "[STALE -- ตัวเลขพยากรณ์เก่าถูกระงับ, รัน floodconnect_answer --refresh เพื่อดูค่าสด]"


def _null_stale_forecast_block(fh_forecast: dict, age_text: str) -> None:
    """Mutates one forecast-shaped dict in place (`forward_hazard.forecast` or
    `.forecast_short`, which share the same shape) so every forward-looking
    figure/word is suppressed, while `source`/`trust_tier`/`fetched_at` survive
    so a caller can still see there WAS a forecast and when it was captured."""
    for key in _STALE_FORECAST_FIELDS:
        if key in fh_forecast:
            fh_forecast[key] = None
    fh_forecast["available"] = False
    fh_forecast["status"] = f"STALE snapshot ({age_text} old) -- figures suppressed"


def _recompute_area_freshness(area: dict) -> dict:
    """Walk the one real snapshot shape (`current_local_state.water_balance.staleness`,
    `current_local_state.canals[].staleness`, `forward_hazard`) and overwrite every
    staleness field with `_recompute_staleness`'s live result. Returns a NEW dict
    (never mutates the caller's `area`, which a test may still hold a reference to).

    This fix: staleness of the FORECAST is judged by the forecast's
    own `fetched_at` (when present), never by the whole area's `generated_at_bkk` --
    those two can legitimately differ (a forecast source can fail a refresh while
    everything else in the area succeeds, or vice versa). When stale, every
    forward-looking figure is nulled IN THE DATA -- `forward_hazard.forecast`,
    `.forecast_short`, `.forecast_72h_worst`, and the layer0 in/out rows' own
    third-party-forecast `text_th` strings and `prop_flood_06.forecast_72h_worst_*`
    -- not only suppressed by a CLI print statement."""
    import copy
    out = copy.deepcopy(area)
    cls = out.get("current_local_state") or {}
    wb = cls.get("water_balance")
    if isinstance(wb, dict):
        baked = wb.get("staleness") or {}
        wb["staleness"] = _recompute_staleness(baked.get("observed_at"))
    for canal in cls.get("canals") or []:
        if not isinstance(canal, dict):
            continue
        baked = canal.get("staleness") or {}
        canal["staleness"] = _recompute_staleness(baked.get("observed_at"))

    # 2026-10-04 fix: computed here (not only at the bottom, as
    # before) so the layer0 measured-row marking just below can use it too.
    all_classes = [wb["staleness"]["age_class"]] if isinstance(wb, dict) else []
    all_classes += [c["staleness"]["age_class"] for c in (cls.get("canals") or [])
                    if isinstance(c, dict)]
    order = {"fresh": 0, "stale": 1, "expired": 2}
    overall = max(all_classes, key=lambda c: order.get(c, 2)) if all_classes else "expired"

    # 2026-10-04 fix: a layer0 MEASURED-tagged row (e.g. "ฝนวัดจริง
    # (24 ชม.) 0.0 มม.", tag_th="วัดจากไฟล์ข้อมูล") used to keep that tag unchanged
    # forever -- only the separately-tagged third-party-forecast rows
    # (`_LAYER0_FORECAST_TAG_TH`) got any staleness treatment at all. A measured row
    # has no freshness timestamp of its own in this exported shape either, so (same
    # reasoning as the tier fix above) it inherits the area's own overall
    # water_balance/canals staleness, never a value read as current when the whole
    # area snapshot is already stale/expired.
    if overall != "fresh":
        layer0_for_measured = cls.get("layer0") if isinstance(cls.get("layer0"), dict) else None
        if layer0_for_measured:
            for items_key in ("in_items", "out_items"):
                for row in layer0_for_measured.get(items_key) or []:
                    if (isinstance(row, dict)
                            and row.get("tag_th") not in (_LAYER0_FORECAST_TAG_TH, None)
                            and row.get("tag_th") != "ยังไม่มีคำตอบ"):  # OPEN rows have nothing to mark stale
                        row["stale"] = True
                        row["text_th"] = f"{row.get('text_th', '')} [STALE: {overall}]"

    fh = out.get("forward_hazard")
    fh_stale = True
    age_text = "age unknown"
    if isinstance(fh, dict):
        forecast = fh.get("forecast") if isinstance(fh.get("forecast"), dict) else {}
        forecast_fetched_at = forecast.get("fetched_at")
        fresh_info = _recompute_staleness(
            forecast_fetched_at if forecast_fetched_at else out.get("generated_at_bkk"),
            max_age_h=_lwl.STALE_HOURS,
        )
        fh["recomputed_staleness"] = fresh_info
        fh_stale = fresh_info["stale"]
        age_text = f"{fresh_info['age_h']:.1f}h" if fresh_info["age_h"] is not None else "age unknown"
        if fh_stale:
            # Note: a stale forward-hazard narrative must not read as a
            # current trend -- drop the prose/figures IN THE DATA (every reader of
            # this dict, not only the CLI's own printer), keep the fact that a
            # forecast existed and when it was generated.
            if isinstance(fh.get("forecast"), dict):
                _null_stale_forecast_block(fh["forecast"], age_text)
            if isinstance(fh.get("forecast_short"), dict):
                _null_stale_forecast_block(fh["forecast_short"], age_text)
            worst = fh.get("forecast_72h_worst")
            if isinstance(worst, dict):
                for key in _STALE_FORECAST_72H_FIELDS:
                    if key in worst:
                        worst[key] = None
            fh["note"] = ("stale snapshot ({} old) -- narrative/figures suppressed, "
                           "re-run `floodconnect_answer`/`--refresh` for a live hazard "
                           "read").format(age_text)

            layer0 = cls.get("layer0") if isinstance(cls.get("layer0"), dict) else None
            if layer0:
                for items_key in ("in_items", "out_items"):
                    for row in layer0.get(items_key) or []:
                        if isinstance(row, dict) and row.get("tag_th") == _LAYER0_FORECAST_TAG_TH:
                            row["text_th"] = _STALE_TEXT_TH
                pf06 = layer0.get("prop_flood_06")
                if isinstance(pf06, dict):
                    pf06["forecast_72h_worst_text_th"] = _STALE_TEXT_TH
                    pf06["forecast_72h_worst_value_mm"] = None
                    pf06["forecast_72h_worst_model_th"] = None
                    pf06["forecast_72h_items_th"] = None

    # 2026-10-04 fix: `layer0.prop_flood_06.tier`/`tier_color`/
    # `tier_word_th` were baked at build time and never recomputed at MCP-call time --
    # a caller could be served a RED tier colour from a build that is now hours/days
    # old, with no staleness flag on the colour itself (only the unrelated forecast
    # sub-fields got this treatment). Gated on the SAME overall water_balance/canals
    # age_class computed just above -- the tier figure has no freshness timestamp of
    # its own in the exported shape, so it inherits the area's own staleness, never a
    # second, independently-invented cutoff.
    if overall != "fresh":
        pf06_tier = (cls.get("layer0") or {}).get("prop_flood_06") \
            if isinstance(cls.get("layer0"), dict) else None
        if isinstance(pf06_tier, dict):
            pf06_tier["tier_word_th"] = _STALE_TEXT_TH
            pf06_tier["tier_color"] = None
            pf06_tier["tier_stale"] = True
            pf06_tier["tier_stale_note"] = (
                f"tier baked at build time ({overall}), never recomputed against this "
                "run's own wall-clock -- re-run `floodconnect_answer`/`--refresh` for a "
                "live tier read")

    out["data_freshness"] = {
        "overall_age_class": overall,
        "oldest_field": None,
        "computed_via": "recomputed at MCP call time against real wall-clock now "
                         "(recompute fix) -- never the baked build-time snapshot value",
        "recomputed_at": _dt.datetime.now(_dt.timezone.utc).isoformat(),
    }
    out["snapshot"] = True
    out["snapshot_generated_at"] = area.get("generated_at_bkk")
    return out


